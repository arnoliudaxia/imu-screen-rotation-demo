import binascii
import json
import math
from pathlib import Path
import struct
import unittest

from imu_reader.protocols import StreamParser, crc8, crc16, checksum


def fdi(kind, payload, seq=17):
    hdr = bytes((0xfc, kind, len(payload), seq))
    return hdr + bytes((crc8(hdr),)) + crc16(payload).to_bytes(2, 'big') + payload + b'\xfd'


def tlv(kind, fmt, *values):
    data = struct.pack(fmt, *values)
    return bytes((kind, len(data))) + data


def yes(payload):
    content = struct.pack('<HB', 42, len(payload)) + payload
    return b'\x59\x53' + content + checksum(content)


class ProtocolTests(unittest.TestCase):
    def test_crc_against_driver_tables(self):
        t8, t16 = json.loads((Path(__file__).parent / 'crc_tables.json').read_text())
        self.assertEqual([crc8(bytes([i])) for i in range(256)], t8)
        self.assertEqual([crc16(bytes([i])) for i in range(256)], t16)
        self.assertEqual(crc8(b'123456789'), 0xa1)
        self.assertEqual(crc16(b'123456789'), 0x31c3)
        self.assertEqual(crc16(b'longer payload'), binascii.crc_hqx(b'longer payload', 0))

    def test_recorded_fdilink_frame(self):
        # Frame from the earlier read-only capture; not generated by these CRC routines.
        frame = bytes.fromhex('fc 40 38 85 ba 18 89 a8 86 ac 3c 00 62 e1 ba 6e 00 b4 bc a3 72 ad be b0 8a ee bf cf 79 19 c1 00 80 59 c3 00 00 49 c3 00 40 09 44 1c 11 17 42 80 e6 c5 47 1c 11 17 42 f9 32 7f 20 00 00 00 00 fd')
        p = StreamParser()
        result = p.feed(frame)
        self.assertEqual((p.good, p.bad), (1, 0))
        self.assertEqual(result[0][0], 'FDILink')
        self.assertAlmostEqual(result[0][1]['temperature_c'], 37.7667, places=2)

    def test_fdi_fields(self):
        p = StreamParser()
        imu = fdi(0x40, struct.pack('<12fq', 1,2,3, 4,5,6, 7,8,9, 25, 1000,20,1234))
        ah = fdi(0x41, struct.pack('<10fq', 1,2,3, math.pi/2, -.25, 1, .5,.5,.5,.5, 4567))
        result = p.feed(imu+ah)
        self.assertEqual(len(result), 2)
        a, b = result[0][1], result[1][1]
        self.assertEqual((a['gyro_y'],a['acc_z'],a['mag_x'],a['temperature_c'],a['device_time_us']), (2,6,7,25,1234))
        self.assertAlmostEqual(b['roll_deg'], 90, places=4)
        self.assertAlmostEqual(b['pitch_deg'], math.degrees(-.25), places=4)
        self.assertEqual((b['q_w'],b['q_x'],b['q_y'],b['q_z']), (.5,.5,.5,.5))
        self.assertEqual(p.protocol, 'FDILink')

    def test_yes_fields(self):
        payload = (tlv(0x10, '<3i', 1000000, -2000000, 9800000) +
                   tlv(0x20, '<3i', 180000000, -90000000, 0) +
                   tlv(0x40, '<3i', 1000000, 2000000, -3000000) +
                   tlv(0x41, '<4i', 1000000, 100000, 200000, 300000) +
                   tlv(0x31, '<3i', 1000, 2000, -3000) +
                   tlv(0x30, '<3i', 1000000, 0, 0) + tlv(1, '<h', -1234) +
                   bytes((0xee, 3, 9, 8, 7)))
        result = StreamParser().feed(yes(payload))[0][1]
        self.assertEqual((result['pitch_deg'],result['roll_deg'],result['yaw_deg']), (1,2,-3))
        self.assertAlmostEqual(result['gyro_x'], math.pi)
        self.assertAlmostEqual(result['gyro_y'], -math.pi/2)
        self.assertEqual((result['acc_x'], result['acc_y']), (1,-2))
        self.assertEqual((result['q_w'], result['q_z']), (1,.3))
        self.assertEqual((result['mag_x'],result['mag_z'],result['mag_norm_x']), (1,-3,1))
        self.assertEqual(result['temperature_c'], -12.34)

    def test_noise_fragments_and_multiple(self):
        a = yes(tlv(0x40, '<3i', 1000000, 2000000, 3000000))
        b = fdi(0x40, struct.pack('<12fq', *range(12), 42))
        stream = b'noise\x59\x00\xfc\x01\x02\x03\x00' + a + b + a
        for step in (1, 2, 7, 1000):
            p = StreamParser(); frames = []
            for i in range(0,len(stream),step): frames.extend(p.feed(stream[i:i+step]))
            self.assertEqual([x[0] for x in frames], ['YESENSE','FDILink','YESENSE'])
            self.assertEqual(p.good, 3)

    def test_corrupt_resync_and_tlv(self):
        frame = yes(tlv(0x40, '<3i', 1, 2, 3))
        bad = bytearray(frame); bad[-1] ^= 1
        f = fdi(0x40, struct.pack('<12fq', *range(12), 99))
        for index in (4, 5, 8, -1):
            broken = bytearray(f); broken[index] ^= 1
            p = StreamParser()
            frames = p.feed(bytes(broken) + f)
            self.assertEqual(len(frames), 1, index)
            self.assertGreaterEqual(p.bad, 1)
        p = StreamParser()
        # Truncated TLV with valid checksum must not decode partially.
        self.assertEqual(len(p.feed(bad + yes(b'\x10\x0c\x01') + frame)), 1)
        self.assertGreaterEqual(p.bad, 2)

    def test_unknown_fdi_and_nonfinite(self):
        p = StreamParser()
        self.assertEqual(p.feed(fdi(0x99, b'hello'))[0][1], {})
        vals = [float('nan')] + [0.0]*11
        self.assertNotIn('gyro_x', p.feed(fdi(0x40, struct.pack('<12fq', *vals, 0)))[0][1])


if __name__ == '__main__': unittest.main()
